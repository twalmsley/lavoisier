//! The code generator: emits a complete, buildable model crate downstream of
//! `model-core`, in the cs1-pot-of-tea house style.
//!
//! * Deterministic and idempotent: output is a pure function of the `.lav`
//!   text (plus the model-core path) - no timestamps, no map-order
//!   dependence; two runs are byte-identical.
//! * Every generated item carries a `// lav: <file>:<line>` breadcrumb; flow
//!   statements and balance asserts carry theirs on (or directly above) the
//!   very line a Rust diagnostic will cite, so an E0080/E0277 is navigable
//!   back to the notation.
//! * The greppable discipline survives generation: `/// REQ-NNN:` first
//!   lines (inside `requirement!`, where trace.sh reads them), `Satisfies:`
//!   tags on items outside macro invocations (F-037) backed by `satisfies!`
//!   (F-020), `Verifies:` tags on the generated flow tests, one-line process
//!   signatures (R10 rule 4), and `Placeholder:` lines on boundary objects.

use crate::ast::*;
use crate::check::{Checked, GenStmt, pretty_num};

/// A generated file: (path relative to the crate dir, contents).
pub type GenFile = (String, String);

/// `MainsTap` → `mains_tap`.
fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(ch.to_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

/// `cs1-slice` → `cs1_slice`.
fn crate_ident(name: &str) -> String {
    name.replace('-', "_")
}

/// The const-generic parameter list of a resource: extras then `V`.
fn res_consts(r: &Resource) -> Vec<String> {
    let mut v = r.extra_consts.clone();
    if r.kind == ResKind::Container {
        v.push("V".to_string());
    }
    v
}

/// `<const A: u64, const V: u64>` (empty string when there are none).
fn const_generics(names: &[String]) -> String {
    if names.is_empty() {
        String::new()
    } else {
        format!(
            "<{}>",
            names
                .iter()
                .map(|n| format!("const {}: u64", n))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

/// `<A, V>` (empty string when there are none).
fn const_args(names: &[String]) -> String {
    if names.is_empty() {
        String::new()
    } else {
        format!("<{}>", names.join(", "))
    }
}

fn breadcrumb(lav: &str, line: usize, what: &str) -> String {
    format!("// lav: {}:{} ({})\n", lav, line, what)
}

/// Renders one side of a balance for the assert expression (`K::WATER_G`) and
/// for prose (`K.WATER_G`).
fn terms_expr(terms: &[Term]) -> String {
    terms
        .iter()
        .map(|t| match &t.param {
            Some(p) => format!("{}::{}", p, t.konst),
            None => t.konst.clone(),
        })
        .collect::<Vec<_>>()
        .join(" + ")
}
fn terms_prose(terms: &[Term]) -> String {
    terms
        .iter()
        .map(|t| match &t.param {
            Some(p) => format!("{}.{}", p, t.konst),
            None => t.konst.clone(),
        })
        .collect::<Vec<_>>()
        .join(" + ")
}

/// Generates the whole crate. `lav` is the notation path as it should appear
/// in breadcrumbs; `model_core` is the path dependency written into
/// Cargo.toml, relative to the generated crate directory.
pub fn generate(checked: &Checked, lav: &str, model_core: &str) -> Vec<GenFile> {
    let m = checked.model;
    let mut files = Vec::new();
    files.push(("Cargo.toml".to_string(), gen_cargo(m, lav, model_core)));
    files.push(("src/lib.rs".to_string(), gen_lib(m, lav)));
    files.push(("src/characteristics.rs".to_string(), gen_characteristics(m, lav)));
    files.push(("src/requirements.rs".to_string(), gen_requirements(m, lav)));
    files.push(("src/resources.rs".to_string(), gen_resources(checked, lav)));
    files.push(("src/flows.rs".to_string(), gen_flows(checked, lav)));
    if !m.flows.is_empty() {
        files.push(("tests/flows.rs".to_string(), gen_flow_tests(m, lav)));
    }
    files
}

const HEADER: &str = "GENERATED by lavc - DO NOT EDIT. Edit the notation and regenerate\n\
                      (the committed crate is gated by regenerate-and-diff, so hand edits fail CI).";

fn header(lav: &str) -> String {
    format!(
        "// {}\n// Source notation: {}\n",
        HEADER.replace('\n', "\n// "),
        lav
    )
}

fn gen_cargo(m: &Model, lav: &str, model_core: &str) -> String {
    format!(
        "# {}\n# Source notation: {}\n\n[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2024\"\ndescription = \"{}\"\n\n[features]\n# The kernel macros expand a `test_fixture()` constructor behind the invoking\n# crate's `test-support` feature (R1, F-004), so the crate declares it; it is\n# never enabled by this generated model.\ntest-support = []\n\n[dependencies]\nmodel-core = {{ path = \"{}\" }}\n\n[workspace]\n",
        HEADER.replace('\n', "\n# "),
        lav,
        m.name,
        m.doc,
        model_core
    )
}

fn gen_lib(m: &Model, lav: &str) -> String {
    let mut s = header(lav);
    s.push_str(&breadcrumb(lav, m.line, &format!("model {}", m.name)));
    s.push_str(&format!("//! # {} - generated model crate (EXP-14)\n//!\n//! {}\n//!\n", m.name, m.doc));
    s.push_str(
        "//! Generated from the `.lav` notation; every item carries a `// lav:`\n\
         //! breadcrumb linking back to its notation line. The crate carries the R1\n\
         //! conservation regime via the model-core kernel macros: conservation\n\
         //! asserts fire at monomorphization (F-001) - `cargo check` and editor\n\
         //! diagnostics will not show them; `cargo build`/`cargo test` do.\n\n",
    );
    s.push_str("#![forbid(unsafe_code)]\n#![deny(unused_must_use)]\n#![deny(let_underscore_drop)]\n#![warn(missing_docs)]\n\n");
    s.push_str("pub mod characteristics;\npub mod flows;\npub mod requirements;\npub mod resources;\n");
    s
}

fn gen_characteristics(m: &Model, lav: &str) -> String {
    let mut s = header(lav);
    s.push_str("//! Characteristic traits (R6), generated from the notation. Requirement\n//! traits in [`crate::requirements`] are bounds over these, never over\n//! concrete resource types (F-019).\n\n");
    // Imports: extraction signatures name the permit and the returned vessel.
    let mut imports: Vec<String> = Vec::new();
    for ch in &m.characteristics {
        if let Some(ex) = &ch.extraction {
            imports.push(format!("{}Permit", ch.name));
            imports.push(ex.returns.clone());
        }
    }
    imports.sort();
    imports.dedup();
    if !imports.is_empty() {
        s.push_str(&format!("use crate::resources::{{{}}};\n\n", imports.join(", ")));
    }
    s.push_str(
        "/// Seals the generated characteristics (F-026): only this crate's declared\n\
         /// carrier states may implement them, so they cannot be used to smuggle\n\
         /// unconserved resources past a requirement bound.\n\
         pub(crate) mod sealed {\n    /// Implemented only for this crate's declared carrier states.\n    pub trait Sealed {}\n}\n",
    );
    for ch in &m.characteristics {
        s.push('\n');
        s.push_str(&breadcrumb(lav, ch.line, &format!("characteristic {} on {}", ch.name, ch.on)));
        s.push_str(&format!("/// {} (R6)\n", ch.doc));
        s.push_str(&format!(
            "#[diagnostic::on_unimplemented(message = \"`{{Self}}` does not have the `{}` characteristic\", label = \"a resource with the `{}` characteristic is required here\", note = \"the state that carries `{}` is `{}` - check which process produces it (one type per state, R9)\")]\n",
            ch.name, ch.name, ch.name, ch.on
        ));
        s.push_str(&format!("pub trait {}: sealed::Sealed {{\n", ch.name));
        for carry in &ch.carries {
            s.push_str(&format!("    /// {} (R7)\n", carry.doc));
            s.push_str(&format!("    const {}: u64;\n", carry.name));
        }
        if let Some(ex) = &ch.extraction {
            s.push_str(&format!(
                "    /// {} Permit-gated (F-054): callable only inside this crate's\n    /// processes, whose balances account for the carried quantities (R1).\n",
                ex.doc
            ));
            s.push_str(&format!(
                "    fn {}(self, permit: {}Permit) -> {};\n",
                ex.fn_name, ch.name, ex.returns
            ));
        }
        s.push_str("}\n");
    }
    s
}

fn gen_requirements(m: &Model, lav: &str) -> String {
    let mut s = header(lav);
    s.push_str("//! Requirements of the modelled system (R10), generated from the notation.\n//! Each is a named trait via `model_core::requirement!`, with a REQ-phrased\n//! single-line `#[diagnostic::on_unimplemented]` (R10 rule 8, F-044) and a\n//! compile-checked assert helper backing every `Satisfies:` tag (F-020).\n\n");
    let mut chars: Vec<String> = m.requirements.iter().map(|r| r.requires.clone()).collect();
    chars.sort();
    chars.dedup();
    if !chars.is_empty() {
        s.push_str(&format!("use crate::characteristics::{{{}}};\n", chars.join(", ")));
    }
    for r in &m.requirements {
        s.push('\n');
        s.push_str(&breadcrumb(lav, r.line, &format!("requirement {}", r.id)));
        s.push_str("model_core::requirement! {\n");
        s.push_str(&format!("    /// {}: {}\n", r.id, r.sentence));
        s.push_str(&format!(
            "    #[diagnostic::on_unimplemented(message = \"{}\", label = \"{}\", note = \"{}\")]\n",
            r.error, r.label, r.note
        ));
        s.push_str(&format!("    pub trait {}: ({});\n", r.trait_name(), r.requires));
        s.push_str(&format!("    assert = {};\n", r.assert_name()));
        s.push_str("}\n");
    }
    s
}

fn gen_resources(checked: &Checked, lav: &str) -> String {
    let m = checked.model;
    let mut s = header(lav);
    s.push_str("//! The sealed resource family (R1), its boundary (R12) and its processes\n//! (F-031), generated from the notation. One type per processing state (R9).\n\n");

    // Imports.
    let mut char_imports: Vec<String> = m.requirements.iter().map(|r| r.requires.clone()).collect();
    if !m.characteristics.is_empty() {
        char_imports.extend(m.characteristics.iter().map(|c| c.name.clone()));
        char_imports.push("sealed".to_string());
    }
    char_imports.sort();
    char_imports.dedup();
    if !char_imports.is_empty() {
        s.push_str(&format!("use crate::characteristics::{{{}}};\n", char_imports.join(", ")));
    }
    let mut asserts: Vec<String> = m
        .requirements
        .iter()
        .filter(|r| r.example.is_some())
        .map(|r| r.assert_name())
        .collect();
    asserts.sort();
    if !asserts.is_empty() {
        s.push_str("// One line on purpose: the traceability grep (F-021) skips `use` lines.\n");
        s.push_str(&format!("use crate::requirements::{{{}}};\n", asserts.join(", ")));
    }
    if !m.sinks.is_empty() {
        s.push_str("use model_core::boundary::Consumer;\n");
    }
    s.push('\n');

    // --- resource types ------------------------------------------------------
    for r in &m.resources {
        s.push_str(&breadcrumb(
            lav,
            r.line,
            &format!("{} {}", if r.kind == ResKind::Container { "container" } else { "reusable" }, r.name),
        ));
        match r.kind {
            ResKind::Container => {
                s.push_str("model_core::container_resource! {\n");
                s.push_str(&format!("    /// {}\n", r.doc));
                if let Some(p) = &r.placeholder {
                    s.push_str("    ///\n");
                    s.push_str(&format!("    /// Placeholder: {}.\n", p));
                }
                let name = if r.extra_consts.is_empty() {
                    r.name.clone()
                } else {
                    format!(
                        "{}<{}>",
                        r.name,
                        r.extra_consts
                            .iter()
                            .map(|c| format!("const {}: u64", c))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                };
                s.push_str(&format!("    {},\n", name));
                s.push_str(&format!("    unit = \"{}\",\n", r.unit));
                s.push_str(&format!(
                    "    must_use = \"{} is a conserved resource: pass it on or hand it to a Consumer\"\n",
                    r.name
                ));
                s.push_str("}\n\n");
            }
            ResKind::Reusable => {
                s.push_str("model_core::reusable_resource! {\n");
                s.push_str(&format!("    /// {}\n", r.doc));
                if let Some(p) = &r.placeholder {
                    s.push_str("    ///\n");
                    s.push_str(&format!("    /// Placeholder: {}.\n", p));
                }
                s.push_str(&format!("    {},\n", r.name));
                s.push_str(&format!(
                    "    must_use = \"{} is a reusable resource: pass it on or return it to the caller\"\n",
                    r.name
                ));
                s.push_str("}\n\n");
            }
        }
    }

    // --- sources (reusable boundary objects, R15/F-028) ----------------------
    for src in &m.sources {
        s.push_str(&breadcrumb(lav, src.line, &format!("source {}", src.name)));
        s.push_str("model_core::reusable_resource! {\n");
        s.push_str(&format!("    /// {}\n", src.doc));
        if let Some(p) = &src.placeholder {
            s.push_str("    ///\n");
            s.push_str(&format!("    /// Placeholder: {}.\n", p));
        }
        s.push_str(&format!("    {},\n", src.name));
        s.push_str(&format!(
            "    must_use = \"{} is a boundary resource: pass it on like any other resource\"\n",
            src.name
        ));
        s.push_str("}\n\n");
    }

    // --- sinks (`Next = Self`, R15/F-029) ------------------------------------
    for sink in &m.sinks {
        let accepted = m.resources.iter().find(|r| r.name == sink.accepts).unwrap();
        let consts = res_consts(accepted);
        s.push_str(&breadcrumb(lav, sink.line, &format!("sink {}", sink.name)));
        s.push_str(&format!(
            "/// {} `Next = Self` (R15, F-029): legal only at the system boundary,\n/// and it necessarily discards what it consumes.\n",
            sink.doc
        ));
        if let Some(p) = &sink.placeholder {
            s.push_str("///\n");
            s.push_str(&format!("/// Placeholder: {}.\n", p));
        }
        s.push_str(&format!(
            "#[must_use = \"{} is a boundary resource: pass it on like any other resource\"]\n",
            sink.name
        ));
        s.push_str(&format!("pub struct {} {{\n    _seal: (),\n}}\n\n", sink.name));
        s.push_str(&format!(
            "/// The sink accepts `{}` at any magnitude; `Next = Self` (R15).\n",
            sink.accepts
        ));
        s.push_str(&format!(
            "impl{} Consumer<{}{}> for {} {{\n",
            const_generics(&consts),
            sink.accepts,
            const_args(&consts),
            sink.name
        ));
        s.push_str(&format!("    type Next = {};\n", sink.name));
        s.push_str(&format!(
            "    fn consume(self, item: {}{}) -> {} {{\n",
            sink.accepts,
            const_args(&consts),
            sink.name
        ));
        s.push_str("        item.defuse(); // sanctioned consumer role (F-008); unbounded sink discards (F-029)\n        self\n    }\n}\n\n");
    }

    // --- permits and characteristic impls ------------------------------------
    for ch in &m.characteristics {
        if ch.extraction.is_some() {
            s.push_str(&format!(
                "/// The permit gating `{}`'s conserving extraction (the F-054 pattern):\n/// a private field and no public constructor, so only this crate's processes\n/// can call the extraction - it can never vanish resources outside a\n/// balanced process (R1).\npub struct {}Permit {{\n    _seal: (),\n}}\n\n",
                ch.name, ch.name
            ));
        }
        let carrier = m.resources.iter().find(|r| r.name == ch.on).unwrap();
        let consts = res_consts(carrier);
        s.push_str(&breadcrumb(lav, ch.line, &format!("characteristic {} on {}", ch.name, ch.on)));
        s.push_str(&format!(
            "/// `{}` carries `{}` (R6, one type per state R9/F-023); the quantities are\n/// the type's own const parameters (R7).\n",
            ch.on, ch.name
        ));
        s.push_str(&format!(
            "impl{} {} for {}{} {{\n",
            const_generics(&consts),
            ch.name,
            ch.on,
            const_args(&consts)
        ));
        for carry in &ch.carries {
            let from = if carry.from_v { "V" } else { carry.name.as_str() };
            s.push_str(&format!("    const {}: u64 = {};\n", carry.name, from));
        }
        if let Some(ex) = &ch.extraction {
            s.push_str(&format!(
                "    fn {}(self, _permit: {}Permit) -> {} {{\n",
                ex.fn_name, ch.name, ex.returns
            ));
            s.push_str("        // Conserving extraction: the carried quantities continue as the\n        // consuming process's outputs, checked by its balances (R1).\n");
            s.push_str("        self.defuse();\n");
            s.push_str(&format!("        {}::mint()\n    }}\n", ex.returns));
        }
        s.push_str("}\n");
        s.push_str(&format!(
            "impl{} sealed::Sealed for {}{} {{}}\n\n",
            const_generics(&consts),
            ch.on,
            const_args(&consts)
        ));
    }

    // --- satisfying examples (tagged alias + satisfies!, F-020/F-037) --------
    for r in &m.requirements {
        if let Some(ex) = &r.example {
            s.push_str(&breadcrumb(lav, ex.line, &format!("example {} ({})", ex.alias, r.id)));
            s.push_str(&format!("/// {} The alias carries the satisfaction tag because a tag inside a\n/// macro invocation would be dropped silently by trace.sh (F-037).\n///\n/// Satisfies: {}\n", ex.doc, r.id));
            let args = if ex.args.is_empty() {
                String::new()
            } else {
                format!(
                    "<{}>",
                    ex.args.iter().map(|a| pretty_num(*a)).collect::<Vec<_>>().join(", ")
                )
            };
            s.push_str(&format!("pub type {} = {}{};\n", ex.alias, ex.resource, args));
            s.push_str(&format!("model_core::satisfies!({}, {});\n\n", r.assert_name(), ex.alias));
        }
    }

    // --- the boundary module --------------------------------------------------
    s.push_str("/// The creation boundary (R12, F-006): the only production code where the\n/// model's reusables, sources and sinks come into existence.\npub mod boundary {\n");
    {
        let mut imports: Vec<String> = Vec::new();
        for r in &m.resources {
            if r.kind == ResKind::Reusable {
                imports.push(r.name.clone());
            }
        }
        for src in &m.sources {
            imports.push(src.name.clone());
            imports.push(src.resource.clone());
        }
        for sink in &m.sinks {
            imports.push(sink.name.clone());
        }
        imports.sort();
        imports.dedup();
        if !imports.is_empty() {
            s.push_str(&format!("    use super::{{{}}};\n\n", imports.join(", ")));
        }
    }
    for r in m.resources.iter().filter(|r| r.kind == ResKind::Reusable) {
        s.push_str(&breadcrumb(lav, r.line, &format!("reusable {} (boundary entry)", r.name)).replace("// lav", "    // lav"));
        s.push_str(&format!("    /// The `{}` enters the model (R12).\n", r.name));
        if let Some(p) = &r.placeholder {
            s.push_str("    ///\n");
            s.push_str(&format!("    /// Placeholder: {}.\n", p));
        }
        s.push_str(&format!(
            "    pub fn new_{}() -> {} {{\n        {}::mint()\n    }}\n\n",
            snake(&r.name),
            r.name,
            r.name
        ));
    }
    for src in &m.sources {
        s.push_str(&breadcrumb(lav, src.line, &format!("source {} (boundary entry)", src.name)).replace("// lav", "    // lav"));
        s.push_str(&format!("    /// The `{}` source enters the model (R12).\n", src.name));
        if let Some(p) = &src.placeholder {
            s.push_str("    ///\n");
            s.push_str(&format!("    /// Placeholder: {}.\n", p));
        }
        s.push_str(&format!(
            "    pub fn new_{}() -> {} {{\n        {}::mint()\n    }}\n\n",
            snake(&src.name),
            src.name,
            src.name
        ));
        let unit = m
            .resources
            .iter()
            .find(|r| r.name == src.resource)
            .map(|r| r.unit.clone())
            .unwrap_or_default();
        let arg = snake(&src.name);
        s.push_str(&breadcrumb(lav, src.line, &format!("source {} (draw process)", src.name)).replace("// lav", "    // lav"));
        s.push_str(&format!(
            "    /// Draws `TAKE` {} of `{}` from the `{}` (R15: an unbounded source of\n    /// continuous material is a draw-style boundary process, never a `Supplier`\n    /// impl, F-028). The source is returned (R2).\n",
            unit, src.resource, src.name
        ));
        if let Some(p) = &src.placeholder {
            s.push_str("    ///\n");
            s.push_str(&format!("    /// Placeholder: {}.\n", p));
        }
        s.push_str(&format!(
            "    pub fn {}<const TAKE: u64>({}: {}) -> ({}<TAKE>, {}) {{\n        ({}::mint(), {})\n    }}\n\n",
            src.draw_fn, arg, src.name, src.resource, src.name, src.resource, arg
        ));
    }
    for sink in &m.sinks {
        s.push_str(&breadcrumb(lav, sink.line, &format!("sink {} (boundary entry)", sink.name)).replace("// lav", "    // lav"));
        s.push_str(&format!(
            "    /// The `{}` sink enters the model (R12): an empty unbounded sink holds\n    /// nothing, so this is an ordinary public boundary function.\n",
            sink.name
        ));
        if let Some(p) = &sink.placeholder {
            s.push_str("    ///\n");
            s.push_str(&format!("    /// Placeholder: {}.\n", p));
        }
        s.push_str(&format!(
            "    pub fn new_{}() -> {} {{\n        {} {{ _seal: () }}\n    }}\n\n",
            snake(&sink.name),
            sink.name,
            sink.name
        ));
    }
    s.push_str("}\n\n");

    // --- the processes module ---------------------------------------------------
    s.push_str("/// The model's processes (R1, R2): pure by-value transformations. They mint\n/// quantity-bearing values, so they live inside the resource family's module\n/// (F-031). Time is drawn by adjacent `draw_time` processes in the flows,\n/// never in here (F-048).\npub mod processes {\n");
    {
        let mut imports: Vec<String> = Vec::new();
        for p in &m.processes {
            for input in &p.inputs {
                if let ParamTy::Concrete { resource, .. } = &input.ty {
                    imports.push(resource.clone());
                }
            }
            for out in &p.outputs {
                match out {
                    Output::Fresh { resource, .. } => imports.push(resource.clone()),
                    Output::Extracted { resource, extraction, .. } => {
                        imports.push(resource.clone());
                        if let Some(ch) = m
                            .characteristics
                            .iter()
                            .find(|c| c.extraction.as_ref().is_some_and(|e| e.fn_name == *extraction))
                        {
                            imports.push(format!("{}Permit", ch.name));
                        }
                    }
                    Output::PassThrough { .. } => {}
                }
            }
        }
        imports.sort();
        imports.dedup();
        if !imports.is_empty() {
            s.push_str(&format!("    use super::{{{}}};\n", imports.join(", ")));
        }
        let mut reqs: Vec<String> = Vec::new();
        for p in &m.processes {
            for input in &p.inputs {
                if let ParamTy::Generic { requires, .. } = &input.ty {
                    if let Some(r) = m.requirements.iter().find(|r| &r.id == requires) {
                        reqs.push(r.trait_name());
                    }
                }
            }
        }
        reqs.sort();
        reqs.dedup();
        if !reqs.is_empty() {
            s.push_str("    // One line on purpose: the traceability grep (F-021) skips `use` lines.\n");
            s.push_str(&format!("    use crate::requirements::{{{}}};\n", reqs.join(", ")));
        }
        if m.processes.iter().any(|p| {
            p.inputs.iter().any(|i| matches!(i.ty, ParamTy::Person { .. }))
        }) {
            s.push_str("    use model_core::common::Person;\n");
        }
        s.push('\n');
    }
    for p in &m.processes {
        let sig = &checked.sigs[&p.name];
        s.push_str(&breadcrumb(lav, p.line, &format!("process {}", p.name)).replace("// lav", "    // lav"));
        s.push_str(&format!("    /// {}\n", p.doc));
        if !p.balances.is_empty() {
            s.push_str("    ///\n    /// Conservation (R3/R15), checked at compile time, firing at\n    /// monomorphization (F-001): `cargo check` and editor diagnostics will not\n    /// show a violation - `cargo build`/`cargo test` do.\n");
            for b in &p.balances {
                s.push_str(&format!(
                    "    /// * {}: {} = {}\n",
                    b.unit,
                    terms_prose(&b.lhs),
                    terms_prose(&b.rhs)
                ));
            }
        }
        let req_ids: Vec<&str> = p
            .inputs
            .iter()
            .filter_map(|i| match &i.ty {
                ParamTy::Generic { requires, .. } => Some(requires.as_str()),
                _ => None,
            })
            .collect();
        if !req_ids.is_empty() {
            s.push_str("    ///\n");
            s.push_str(&format!("    /// Satisfies: {}\n", req_ids.join(", ")));
        }
        // Signature, on ONE line (R10 rule 4: requirement bounds stay on the
        // `fn`-name line; grep has no scope awareness).
        let mut generics: Vec<String> = sig.const_params.iter().map(|c| format!("const {}: u64", c)).collect();
        for (ident, req_id) in &sig.generics {
            let tn = m
                .requirements
                .iter()
                .find(|r| &r.id == req_id)
                .map(|r| r.trait_name())
                .unwrap_or_default();
            generics.push(format!("{}: {}", ident, tn));
        }
        let gen_str = if generics.is_empty() {
            String::new()
        } else {
            format!("<{}>", generics.join(", "))
        };
        let params: Vec<String> = p
            .inputs
            .iter()
            .map(|i| match &i.ty {
                ParamTy::Person { budget } => format!("{}: Person<{}>", i.var, budget),
                ParamTy::Concrete { resource, consts } => {
                    format!("{}: {}{}", i.var, resource, const_args(consts))
                }
                ParamTy::Generic { ident, .. } => format!("{}: {}", i.var, ident),
            })
            .collect();
        let outs: Vec<String> = p
            .outputs
            .iter()
            .map(|o| match o {
                Output::PassThrough { var, .. } => {
                    let input = p.inputs.iter().find(|i| &i.var == var).unwrap();
                    match &input.ty {
                        ParamTy::Person { budget } => format!("Person<{}>", budget),
                        ParamTy::Concrete { resource, consts } => {
                            format!("{}{}", resource, const_args(consts))
                        }
                        ParamTy::Generic { ident, .. } => ident.clone(),
                    }
                }
                Output::Fresh { resource, consts, .. } => format!("{}{}", resource, const_args(consts)),
                Output::Extracted { resource, .. } => resource.clone(),
            })
            .collect();
        let ret = if outs.len() == 1 {
            outs[0].clone()
        } else {
            format!("({})", outs.join(", "))
        };
        s.push_str(&format!(
            "    pub fn {}{}({}) -> {} {{\n",
            p.name,
            gen_str,
            params.join(", "),
            ret
        ));
        for b in &p.balances {
            s.push_str(&breadcrumb(lav, b.line, &format!("balance {}", b.unit)).replace("// lav", "        // lav"));
            s.push_str(&format!(
                "        const {{ assert!({} == {}, \"{}: {} must equal {} - the amounts entering {} must sum exactly to the amounts leaving it\") }};\n",
                terms_expr(&b.lhs),
                terms_expr(&b.rhs),
                b.label,
                terms_prose(&b.lhs),
                terms_prose(&b.rhs),
                p.name
            ));
        }
        // Consume the inputs that do not pass through.
        let mut body_note = false;
        for input in &p.inputs {
            let passed = p
                .outputs
                .iter()
                .any(|o| matches!(o, Output::PassThrough { var, .. } if var == &input.var));
            let extracted = p
                .outputs
                .iter()
                .any(|o| matches!(o, Output::Extracted { from_var, .. } if from_var == &input.var));
            if passed || extracted {
                continue;
            }
            if !body_note {
                s.push_str("        // Conserving transforms (R1): each consumed input's quantity\n        // continues in the outputs; the balances above account for it.\n");
                body_note = true;
            }
            match &input.ty {
                ParamTy::Concrete { resource, .. } => {
                    let r = m.resources.iter().find(|r| &r.name == resource).unwrap();
                    if r.kind == ResKind::Container {
                        s.push_str(&format!("        {}.defuse();\n", input.var));
                    } else {
                        s.push_str(&format!("        let {} {{ _seal: () }} = {};\n", resource, input.var));
                    }
                }
                ParamTy::Person { .. } | ParamTy::Generic { .. } => {}
            }
        }
        // Extractions.
        for out in &p.outputs {
            if let Output::Extracted { var, extraction, from_var, .. } = out {
                let ch = m
                    .characteristics
                    .iter()
                    .find(|c| c.extraction.as_ref().is_some_and(|e| e.fn_name == *extraction))
                    .unwrap();
                s.push_str(&format!(
                    "        let {} = {}.{}({}Permit {{ _seal: () }});\n",
                    var, from_var, extraction, ch.name
                ));
            }
        }
        // The output tuple.
        let exprs: Vec<String> = p
            .outputs
            .iter()
            .map(|o| match o {
                Output::PassThrough { var, .. } => var.clone(),
                Output::Fresh { resource, .. } => format!("{}::mint()", resource),
                Output::Extracted { var, .. } => var.clone(),
            })
            .collect();
        if exprs.len() == 1 {
            s.push_str(&format!("        {}\n", exprs[0]));
        } else {
            s.push_str(&format!("        ({})\n", exprs.join(", ")));
        }
        s.push_str("    }\n\n");
    }
    s.push_str("}\n");
    s
}

fn gen_flows(checked: &Checked, lav: &str) -> String {
    let m = checked.model;
    let mut s = header(lav);
    s.push_str("//! Composite flows (R9: connections, not sequences), one top-level `pub fn`\n//! per flow (the R20 convention). Each returns its complete final accounting\n//! (R1). Time is drawn by adjacent `draw_time` processes (F-048), recorded\n//! into the flow's single History attributed to the process name (R16).\n\n");

    // Imports, computed from the statements actually generated.
    let mut b_fns: Vec<String> = Vec::new();
    let mut p_fns: Vec<String> = Vec::new();
    let mut types: Vec<String> = Vec::new();
    let mut use_send = false;
    let mut use_person = false;
    let mut use_history = false;
    for (f, fe) in m.flows.iter().zip(&checked.flows) {
        for st in &fe.stmts {
            match st {
                GenStmt::Person { .. } => use_person = true,
                GenStmt::History { .. } => use_history = true,
                GenStmt::NewReusable { ty, .. } | GenStmt::NewSource { ty, .. } | GenStmt::NewSink { ty, .. } => {
                    b_fns.push(format!("new_{}", snake(ty)))
                }
                GenStmt::Take { draw_fn, .. } => b_fns.push(draw_fn.clone()),
                GenStmt::Spend { .. } => {
                    use_person = true;
                    use_history = true;
                }
                GenStmt::Do { process, .. } => p_fns.push(process.clone()),
                GenStmt::Send { .. } => use_send = true,
            }
        }
        let _ = f;
        for (_, ty) in &fe.end {
            let base = ty.split('<').next().unwrap().to_string();
            if base != "Person" && base != "History" {
                types.push(base);
            }
        }
    }
    b_fns.sort();
    b_fns.dedup();
    p_fns.sort();
    p_fns.dedup();
    types.sort();
    types.dedup();
    if !b_fns.is_empty() {
        s.push_str(&format!("use crate::resources::boundary::{{{}}};\n", b_fns.join(", ")));
    }
    if !p_fns.is_empty() {
        s.push_str(&format!("use crate::resources::processes::{{{}}};\n", p_fns.join(", ")));
    }
    if !types.is_empty() {
        s.push_str(&format!("use crate::resources::{{{}}};\n", types.join(", ")));
    }
    if use_send {
        s.push_str("use model_core::boundary::send_to;\n");
    }
    if use_person {
        s.push_str("use model_core::common::Person;\nuse model_core::common::boundary::new_person;\nuse model_core::common::processes::draw_time;\n");
    }
    if use_history {
        s.push_str("use model_core::history::History;\nuse model_core::history::boundary::new_history;\nuse model_core::history::processes::record;\n");
    }

    for (f, fe) in m.flows.iter().zip(&checked.flows) {
        s.push('\n');
        s.push_str(&breadcrumb(lav, f.line, &format!("flow {}", f.name)));
        s.push_str(&format!("/// {}\n///\n/// The returned tuple is the flow's complete final accounting (R1): every\n/// reusable, boundary object and record comes back; every conserved quantity\n/// has reached a sink inside the flow.\n", f.doc));
        let ret: Vec<String> = fe.end.iter().map(|(_, ty)| ty.clone()).collect();
        s.push_str(&format!("pub fn {}() -> ({}) {{\n", f.name, ret.join(", ")));
        for st in &fe.stmts {
            match st {
                GenStmt::Person { var, budget, lav: l } => s.push_str(&format!(
                    "    let {} = new_person::<{}>(); // lav: {}:{}\n",
                    var,
                    pretty_num(*budget),
                    lav,
                    l
                )),
                GenStmt::History { var, lav: l } => s.push_str(&format!(
                    "    let {} = new_history(); // lav: {}:{}\n",
                    var, lav, l
                )),
                GenStmt::NewReusable { var, ty, lav: l }
                | GenStmt::NewSource { var, ty, lav: l }
                | GenStmt::NewSink { var, ty, lav: l } => s.push_str(&format!(
                    "    let {} = new_{}(); // lav: {}:{}\n",
                    var,
                    snake(ty),
                    lav,
                    l
                )),
                GenStmt::Take { var, amount, from, draw_fn, lav: l } => s.push_str(&format!(
                    "    let ({}, {}) = {}::<{}>({}); // lav: {}:{}\n",
                    var,
                    from,
                    draw_fn,
                    pretty_num(*amount),
                    from,
                    lav,
                    l
                )),
                GenStmt::Spend { person, take, left, budget, process, history, lav: l } => {
                    s.push_str(&format!(
                        "    let (labour, {}) = draw_time::<{}, {}, {}>({}); // lav: {}:{} (spend on {})\n",
                        person,
                        pretty_num(*take),
                        pretty_num(*left),
                        pretty_num(*budget),
                        person,
                        lav,
                        l,
                        process
                    ));
                    s.push_str(&format!(
                        "    let {} = record({}, \"{}\", labour); // lav: {}:{}\n",
                        history, history, process, lav, l
                    ));
                }
                GenStmt::Do { outs, process, turbofish, args, lav: l } => {
                    let tf = if turbofish.is_empty() {
                        String::new()
                    } else {
                        format!("::<{}>", turbofish.join(", "))
                    };
                    let lhs = if outs.len() == 1 {
                        outs[0].clone()
                    } else {
                        format!("({})", outs.join(", "))
                    };
                    s.push_str(&format!(
                        "    let {} = {}{}({}); // lav: {}:{}\n",
                        lhs,
                        process,
                        tf,
                        args.join(", "),
                        lav,
                        l
                    ));
                }
                GenStmt::Send { var, to, lav: l } => s.push_str(&format!(
                    "    let {} = send_to({}, {}); // lav: {}:{}\n",
                    to, to, var, lav, l
                )),
            }
        }
        let vars: Vec<String> = fe.end.iter().map(|(v, _)| v.clone()).collect();
        s.push_str(&format!("    ({})\n}}\n", vars.join(", ")));
    }
    s
}

fn gen_flow_tests(m: &Model, lav: &str) -> String {
    let ident = crate_ident(&m.name);
    let mut s = header(lav);
    s.push_str("//! Integration tests (R5): one per flow, outside the privacy boundary -\n//! exactly the discipline a downstream user of the model lives under.\n\n");
    for f in &m.flows {
        s.push('\n');
        s.push_str(&breadcrumb(lav, f.line, &format!("flow {} (integration test)", f.name)));
        s.push_str(&format!(
            "/// {} The flow type-checks and its final accounting comes back (R1, R9).\n",
            f.doc
        ));
        if !f.verifies.is_empty() {
            s.push_str("///\n");
            s.push_str(&format!("/// Verifies: {}\n", f.verifies.join(", ")));
        }
        s.push_str("#[test]\n");
        s.push_str(&format!(
            "fn flow_{}_accounts_for_everything() {{\n    let _accounted = {}::flows::{}();\n}}\n",
            f.name, ident, f.name
        ));
    }
    s
}
