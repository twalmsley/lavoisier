#!/usr/bin/env python3
"""Generates src/peano_aliases.rs and src/binary_aliases.rs.

macro_rules! cannot synthesize identifiers (there is no `paste` on stable
without a dependency), so the alias *names* N0..N1000 have to exist in the
source somewhere. This script writes them out once; the macros in the
generated files do the structural work. Re-run after changing MAX.
"""

import os

MAX = 1000
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")


def peano() -> str:
    lines = [
        "//! Aliases `N0`..=`N{}` for the Peano encoding.".format(MAX),
        "//! GENERATED by tools/gen_aliases.py — do not edit by hand.",
        "",
        "use crate::peano::{Succ, Zero};",
        "",
        "/// Defines each alias as the successor of the previous one.",
        "/// Deliberately non-recursive (a single repetition), so defining",
        "/// 1000 aliases does not consume macro recursion depth.",
        "macro_rules! nats {",
        "    ($($prev:ident => $cur:ident;)*) => {",
        "        $(pub type $cur = Succ<$prev>;)*",
        "    };",
        "}",
        "",
        "pub type N0 = Zero;",
        "",
        "nats! {",
    ]
    for i in range(1, MAX + 1):
        lines.append("    N{} => N{};".format(i - 1, i))
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def binary() -> str:
    lines = [
        "//! Aliases `BN0`..=`BN{}` for the binary encoding.".format(MAX),
        "//! GENERATED by tools/gen_aliases.py — do not edit by hand.",
        "",
        "use crate::binary::{UInt, UTerm, B0, B1};",
        "",
        "/// Builds a binary number from its bits, most significant bit first:",
        "/// `uint!(1 1 0)` is 6. Recursion depth is the bit count (~10 for 1000).",
        "macro_rules! uint {",
        "    (@acc $acc:ty;) => { $acc };",
        "    (@acc $acc:ty; 0 $($rest:tt)*) => { uint!(@acc UInt<$acc, B0>; $($rest)*) };",
        "    (@acc $acc:ty; 1 $($rest:tt)*) => { uint!(@acc UInt<$acc, B1>; $($rest)*) };",
        "    ($($b:tt)+) => { uint!(@acc UTerm; $($b)+) };",
        "}",
        "",
        "pub type BN0 = UTerm;",
    ]
    for i in range(1, MAX + 1):
        bits = " ".join(format(i, "b"))
        lines.append("pub type BN{} = uint!({});".format(i, bits))
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    with open(os.path.join(SRC, "peano_aliases.rs"), "w") as f:
        f.write(peano())
    with open(os.path.join(SRC, "binary_aliases.rs"), "w") as f:
        f.write(binary())
    print("wrote peano_aliases.rs and binary_aliases.rs (MAX = {})".format(MAX))


if __name__ == "__main__":
    main()
