//! # cs2-puncture-repair — case study CS-2: bicycle puncture repair
//!
//! The second spec→model round trip: this crate implements, downstream of
//! `model-core`, the agreed natural-language specification
//! `case-studies/cs2-puncture-repair/SPEC.md` (v0.2, agreed). One person
//! repairs a punctured rear wheel at a community bike workshop. CS-2
//! exercises the three features CS-1 deliberately avoided: a **fallible
//! process with provisioned rework** (the patch can fail — R17, bounded to
//! two attempts by the kit's two patches and the two provisioned outcome
//! tokens, F-050), **qualification** (the workstand may be used only by an
//! inducted member — R18), and **money** (a spare tube is bought at the parts
//! counter at its exact listed price — R19). The patch kit is a nested
//! container: two discrete patches held as a type-level list *and* a 30 g
//! cement tube carried as the kit's own continuous magnitude, drawn 1 g per
//! attempt through the kit's boundary.
//!
//! ## Module map
//!
//! | Module | Contents |
//! |---|---|
//! | [`characteristics`] | Characteristic traits (R6): [`characteristics::Inducted`] (the R18 qualification marker over `Qualified<Induction, MS>`), the sealed, quantity-carrying [`characteristics::PunctureLocated`] and [`characteristics::Airtight`] (permit-gated conserving extractions, F-054), and the sink/vendor markers [`characteristics::WasteStreamConsumer`] and [`characteristics::ExactPriceCounter`] |
//! | [`requirements`] | The five modelled-system requirements of SPEC.md §2 as R10 requirement traits via `model_core::requirement!`, each with a REQ-phrased `on_unimplemented` (R10 rule 8, F-044). The workspace trace namespace is global (F-053): the pilot owns REQ-001..005 and CS-1 owns REQ-006..009, so CS-2 starts at REQ-010 exactly as SPEC.md §2 numbers it — no id mapping needed this time |
//! | [`resources`] | The sealed resource family (R1): the wheel/tube/patch states (one type per state, R9, masses in the types), the nested patch kit, cash and the wallet (R19), the workstand and pump reusables, the `PatchOutcome` token (R17), the `PartsCounter` vendor, and the unbounded waste-stream/recycling/owner sinks — with `boundary` and `processes` child modules (F-006, F-031) |
//! | [`flows`] | The repair flow (R17/F-050): both orderings, returning the `#[must_use]` per-path outcome grouping [`flows::RepairOutcome`] — one variant per path, because the three paths end with different wheel masses, budgets and wallet states (F-046/F-050) |
//!
//! Flows (SPEC.md §6) are exercised as integration tests: `tests/flows.rs`
//! drives all three paths through [`flows::repair_wheel`] (and the
//! wallet-readied-early ordering variant) and accounts for everything at each
//! path's end (R1, R9).
//!
//! ## Conservation regime (R1)
//!
//! This crate carries the full obligations listed in `model-core`'s crate
//! docs: `recursion_limit`, `forbid(unsafe_code)`, the must-use/underscore
//! lints, tripwire `Drop`s on every consumable (generated by the kernel
//! macros), and CI clippy under `-D warnings` with the workspace
//! `clippy.toml` ban list. Never write `let _ = <resource>`, and ignore
//! compiler fix-its suggesting borrows, clones, drops or `.expect(…)`
//! (F-007).
//!
//! ## The member's time budget (R15/R18)
//!
//! The member enters at the boundary with the SPEC's 1 800 000 ms budget,
//! already inducted (`qualify::<Induction, _>`, the R18 placeholder boundary
//! process). Every person-process in the flow has an **adjacent**
//! `qualified_draw_time` whose labour is recorded into the single `History`
//! attributed to the process name (R16, F-048); each P3 attempt's draw
//! happens *before* the fallible branch, so failure costs the same time as
//! success (R17). Overspending the budget is a compile error like any
//! overdraw (E0080 at monomorphization, invisible to `cargo check`, F-001).
//! Regression — 240 000 ms of wheel-opening cannot come out of a 200 000 ms
//! budget:
//!
//! ```compile_fail
//! use cs2_puncture_repair::characteristics::Induction;
//! use model_core::common::boundary::{new_person, qualify};
//! use model_core::common::processes::qualified_draw_time;
//!
//! let member = qualify::<Induction, 200_000>(new_person::<200_000>());
//! let (labour, member) = qualified_draw_time::<240_000, 0, 200_000, _>(member);
//! ```
//!
//! ## Traceability (R10)
//!
//! The five requirements are defined in [`requirements`] and reported by the
//! workspace `trace.sh` (a CI gate). REQ-012 is deliberately the first
//! requirement satisfied by **two** types (the checked patched tube *and* the
//! new spare, SPEC.md §8 review decision 7): both carry compile-check-backed
//! doc tags, the first real exercise of the F-055 note that `satisfies!`
//! resolution becomes many-to-many. Tests are tagged with the requirement IDs
//! they verify.

